#!/usr/bin/env python3
"""Mutation proof for BasquinInjector's guards. Writes a transcript; restores the source.

Each row: neuter one guard branch, clear build/test-results, run the module suite, and read the
failing set out of FRESH JUnit XML (never stale XML, never console text).
"""
import glob, hashlib, os, shutil, subprocess, sys, tempfile, xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
SRC = REPO + "/basquin-maven-injector/src/main/java/com/basquin/maven/BasquinInjector.java"
XML = REPO + "/basquin-maven-injector/build/test-results"
OUT = HERE + "/mutation-proof.txt"
# The baseline is a copy of the CURRENT source taken outside the repo; every mutation is applied to a
# fresh copy of it and the file is restored from it, so a crashed run cannot leave the tree mutated.
PRI = os.path.join(tempfile.mkdtemp(prefix="basquin-mutation-"), "BasquinInjector.PRISTINE.java")
shutil.copyfile(SRC, PRI)

# label, expected-test-among-failures, (old, new)
MUTATIONS = [
    # --- already wired into scripts/verify-dd043-pr3.sh's run_guards -----------------------------
    ("skip", "injectsNothingWhenSkipIsSet",
     ("if (Boolean.parseBoolean(props.getProperty(PROP_SKIP)))", "if (false)")),
    ("managed-version", "failsLoudlyWhenDependencyManagementPinsOurGroupToADifferentVersion",
     ("        DependencyManagement dm = p.getModel().getDependencyManagement();",
      "        DependencyManagement dm = null;")),
    ("managed-exclusions", "failsLoudlyWhenDependencyManagementCarriesExclusions",
     ("            if (managed.getExclusions() != null && !managed.getExclusions().isEmpty()) {",
      "            if (false) {")),
    ("declared-version", "failsLoudlyWhenTheProjectDeclaresOurArtifactAtADifferentVersion",
     ("if (declared == null || declared.equals(version))", "if (true)")),
    ("declaration-usability", "failsLoudlyWhenOurArtifactIsDeclaredAtAnUnusableScope",
     ("        if (problem == null) {", "        if (true) {")),
    # --- NEW: the S2 sibling guard. The two entries proposed for run_guards are sibling-scope and
    #     sibling-version; the other three rows prove the accept-side tests bind too. -------------
    ("sibling-scope", "failsLoudlyWhenAnotherBasquinArtifactIsDeclaredAtAnUnusableScope",
     ('            if (!"compile".equals(scope) && !"runtime".equals(scope)) {',
      "            if (false) {")),
    ("sibling-version", "failsLoudlyWhenAnotherBasquinArtifactIsDeclaredAtAConflictingVersion",
     ("            if (declared != null && !declared.equals(version)) {", "            if (false) {")),
    ("sibling-whole", "failsLoudlyWhenAnotherBasquinArtifactIsDeclaredAtAConflictingVersion",
     ("    private void failOnUnusableSiblingDeclaration(MavenProject p, String version)\n"
      "            throws MavenExecutionException {\n",
      "    private void failOnUnusableSiblingDeclaration(MavenProject p, String version)\n"
      "            throws MavenExecutionException {\n        if (true) { return; }\n")),
    ("sibling-overstrict", "acceptsAnotherBasquinArtifactDeclaredAtTheInjectedVersion",
     ("            if (declared != null && !declared.equals(version)) {",
      "            if (declared != null) {")),
    ("sibling-widened", "acceptsTheSiblingShapesMeasuredHarmless",
     ("            String declared = d.getVersion();",
      '            if (d.getExclusions() != null && !d.getExclusions().isEmpty()) {\n'
      '                throw new MavenExecutionException("widened", p.getFile());\n            }\n'
      '            if (!"jar".equals(d.getType() == null ? "jar" : d.getType())) {\n'
      '                throw new MavenExecutionException("widened", p.getFile());\n            }\n'
      "            String declared = d.getVersion();")),
]


def md5(p):
    return hashlib.md5(open(p, "rb").read()).hexdigest()


def run_suite():
    shutil.rmtree(XML, ignore_errors=True)
    r = subprocess.run(["./gradlew", ":basquin-maven-injector:test", "--no-daemon", "-q"],
                       cwd=REPO, capture_output=True, text=True)
    xs = sorted(glob.glob(XML + "/**/*.xml", recursive=True))
    total, fails = 0, []
    for x in xs:
        root = ET.parse(x).getroot()
        total += int(root.get("tests", 0))
        for tc in root.iter("testcase"):
            if tc.find("failure") is not None or tc.find("error") is not None:
                fails.append(tc.get("name"))
    return r.returncode, len(xs), total, sorted(fails)


lines = []
w = lines.append
w("# mutation proof — basquin-maven-injector guards")
w("#")
w("# Generated by mutation_proof.py. Every figure below is read from FRESH JUnit XML under")
w("# basquin-maven-injector/build/test-results, which is deleted before each run; a row with")
w("# fresh_xml=0 would mean the suite never ran and therefore that NO verdict exists (round 3's B1).")
w("")
pristine_md5 = md5(PRI)
w(f"pristine source md5: {pristine_md5}")

shutil.copyfile(PRI, SRC)
rc, nxml, total, fails = run_suite()
w(f"baseline (unmutated): gradle_rc={rc} fresh_xml={nxml} tests={total} failing={len(fails)} {fails}")
if rc != 0 or fails:
    w("BASELINE NOT GREEN — everything below is void")
w("")
w(f"{'mutation':<22} {'rc':<3} {'xml':<4} {'tests':<6} {'binds':<6} expected / failing set")
w("-" * 118)

ok = True
for label, expect, (old, new) in MUTATIONS:
    s = open(PRI).read()
    n = s.count(old)
    if n != 1:
        w(f"{label:<22} ANCHOR NOT UNIQUE (occurrences={n}) — mutation not applied")
        ok = False
        continue
    open(SRC, "w").write(s.replace(old, new, 1))
    rc, nxml, total, fails = run_suite()
    binds = expect in fails
    ok = ok and binds and nxml > 0 and rc != 0
    w(f"{label:<22} {rc:<3} {nxml:<4} {total:<6} {'YES' if binds else 'NO':<6} {expect}")
    w(f"{'':<22} {'':<3} {'':<4} {'':<6} {'':<6} failing={fails}")

shutil.copyfile(PRI, SRC)
rc, nxml, total, fails = run_suite()
w("-" * 118)
w(f"restored: source md5={md5(SRC)} (== pristine: {md5(SRC) == pristine_md5})")
w(f"restored suite: gradle_rc={rc} fresh_xml={nxml} tests={total} failing={len(fails)} {fails}")
w("")
w(f"VERDICT: {'every mutation bound to its named test' if ok else 'AT LEAST ONE MUTATION DID NOT BIND'}")
open(OUT, "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
sys.exit(0 if ok and rc == 0 and not fails else 1)
