#!/usr/bin/env python3
"""Regenerate cell-results.txt and citations.txt from logs/ and cells/ — run from this directory.

Nothing in either derived file is hand-typed: rows come from grepping the logs, and every citation is
re-read from its file and required to match, so a drifted line number fails loudly here rather than
silently in prose."""
import os, re, sys

CELLS = ["ctl", "mscore", "mtcore", "moptcore"]
rows, cites = [], []

def cite(path, lineno, expect):
    cites.append((path, lineno, expect))

for cell in CELLS:
    lst = f"logs/{cell}-stock-list.log"
    text = open(lst).read().splitlines()
    core = next((l.split("   ")[-1].strip() for l in text
                 if "com.basquin:basquin-core" in l and "module" in l), "ABSENT")
    outcome = "SUCCESS" if any("BUILD SUCCESS" in l for l in text) else "FAILURE/ABORT"
    guardfired = any("dependencyManagement pins" in l for l in text)
    entries = [l for l in open(f"logs/{cell}-stock-runtime-cp-entries.txt").read().splitlines() if l]
    core_on_rt = any("basquin-core" in e for e in entries)
    g = open(f"logs/{cell}-guarded-list.log").read().splitlines()
    g_out = "SUCCESS" if any("BUILD SUCCESS" in l for l in g) else "ABORT"
    g_fired = any("dependencyManagement pins" in l for l in g)
    rows.append((cell, core, outcome, str(len(entries)), "yes" if core_on_rt else "NO",
                 "fired" if guardfired else "silent", g_out, "fired" if g_fired else "silent"))
    for i, l in enumerate(text, 1):
        if "[basquin-injector]" in l: cite(lst, i, l.strip()[:80])
        if "com.basquin" in l and "module" in l: cite(lst, i, l.strip())
        if "BUILD SUCCESS" in l: cite(lst, i, "BUILD SUCCESS")
    ents = f"logs/{cell}-stock-runtime-cp-entries.txt"
    for i, l in enumerate(entries, 1):
        if "basquin" in l: cite(ents, i, os.path.basename(l))
    gl = f"logs/{cell}-guarded-list.log"
    for i, l in enumerate(g, 1):
        if "dependencyManagement pins" in l: cite(gl, i, l.strip()[:100])
        if "BUILD SUCCESS" in l: cite(gl, i, "BUILD SUCCESS")
        if "com.basquin" in l and "module" in l: cite(gl, i, l.strip())
cc = "logs/ctl-stock-coldcache-list.log"
for i, l in enumerate(open(cc).read().splitlines(), 1):
    if "com.basquin" in l and "module" in l: cite(cc, i, l.strip())
    elif "BUILD SUCCESS" in l: cite(cc, i, "BUILD SUCCESS")
for cell in ["mscore", "mtcore", "moptcore"]:
    p = f"cells/{cell}.pom.xml"
    for i, l in enumerate(open(p).read().splitlines(), 1):
        if "basquin-core" in l or "<scope>" in l or "<optional>" in l: cite(p, i, l.strip())

with open("cell-results.txt", "w") as f:
    f.write("# cell-results — machine-generated from logs/ by regen-derived.py; do not hand-edit\n")
    f.write("# stock = injector compiled from 865ba35 (pre-fix); guarded = injector with the round-7 scope branch\n\n")
    f.write(f"{'cell':10} {'basquin-core resolved as (stock list)':55} {'stock build':12} "
            f"{'rt-cp entries':13} {'core on rt-cp':13} {'stock guard':11} {'guarded build':13} {'guarded guard':13}\n")
    for r in rows:
        f.write(f"{r[0]:10} {r[1]:55} {r[2]:12} {r[3]:13} {r[4]:13} {r[5]:11} {r[6]:13} {r[7]:13}\n")

bad = 0
with open("citations.txt", "w") as f:
    f.write("# citations — machine-generated by regen-derived.py: every file:line cited by README.md /\n")
    f.write("# the shipped javadoc, as 'file:line: expected-text'; each is verified to resolve exactly.\n")
    for p, n, e in cites:
        f.write(f"{p}:{n}: {e}\n")
for p, n, e in cites:
    if e not in open(p).read().splitlines()[n - 1]:
        print(f"CITATION MISMATCH {p}:{n}", file=sys.stderr); bad += 1
print(f"cell-results.txt: {len(rows)} rows; citations.txt: {len(cites)} entries, {bad} mismatches")
sys.exit(1 if bad else 0)
